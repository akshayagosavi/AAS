# Credit Utilisation Composite
master_df['credit_util_composite'] = (
    0.5*master_df['revol_util_pct']
    +
    0.3*master_df['bc_util_pct']
    +
    0.2*master_df['all_util_pct']
)

"""A composite credit utilisation measure was created using weighted utilisation metrics from revolving, bankcard, and overall credit facilities."""

# Delinquency Severity Score
master_df['delinq_severity_score'] = (
    master_df['delinq_2yrs']
    *
    (
        1
        +
        1 /
        master_df[
            'mths_since_last_delinq'
        ].clip(lower=1)
    )
)

"""Delinquency Severity Score combines the number of historical delinquencies with recency information."""

# Enquiry Velocity Score
master_df['enq_velocity_score'] = (
    4*master_df['num_enquiries_30d']
    +
    master_df['num_enquiries_90d']
)

"""Enquiry Velocity Score measures recent credit-seeking behaviour by assigning greater weight to enquiries made within the previous 30 days.The feature was constructed to capture short-term changes in borrower credit demand and assessed against LGD."""

# Correlations
features_b = [
    'credit_util_composite',
    'delinq_severity_score',
    'enq_velocity_score'
]

for col in features_b:
    print(
        col,
        master_df[col].corr(
            master_df['lgd_pct']
        )
    )

"""Q3(c) Income & Collateral Features"""

# Income Stability Ratio
master_df['income_stability_ratio'] = (
    master_df['annual_inc_inr']
    /
    (
        master_df['emp_length_years']
        + 1
    )
)

"""Income Stability Ratio was calculated by dividing annual income by employment tenure. The feature attempts to capture income consistency over the borrower’s employment history."""

# Credit Depth Score
master_df['credit_depth_score'] = (
    master_df['total_acc']
    /
    (
        master_df['credit_hist_years']
        + 1
    )
)

"""Credit Depth Score measures the number of credit accounts relative to credit history length. This feature captures the breadth of borrower credit experience."""

# Collateral Coverage Ratio
master_df['collateral_coverage_ratio'] = (
    master_df['collateral_value_inr']
    /
    (
        master_df['loan_amnt_inr']
        + 1
    )
)

"""Collateral Coverage Ratio was calculated as collateral value divided by loan amount. This feature measures the extent to which collateral can absorb potential losses in the event of default."""

# Correlations
features_c = [
    'income_stability_ratio',
    'credit_depth_score',
    'collateral_coverage_ratio'
]

for col in features_c:
    print(
        col,
        master_df[col].corr(
            master_df['lgd_pct']
        )
    )

