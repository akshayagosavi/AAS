"""Q4(a) VIF Analysis"""

# Select Numeric Features
# Exclude target.
num_cols = df_model.select_dtypes(
    include=np.number
).columns.tolist()

num_cols.remove('lgd_pct')
num_cols.remove('loan_status')

# Fill Missing Values
X = df_model[num_cols].fillna(
    df_model[num_cols].median()
)

X_vif = X.sample(
    n=10000,
    random_state=42
)

print(X_vif.shape)

# Calculate VIF
vif_df = pd.DataFrame()

vif_df['Feature'] = X.columns

vif_df['VIF'] = [
    variance_inflation_factor(
        X.values,
        i
    )
    for i in range(X.shape[1])
]

vif_df.sort_values(
    'VIF',
    ascending=False
)
vif_df

high_vif = vif_df[
    vif_df['VIF'] > 10
]
print(high_vif)

features_keep = vif_df[
    vif_df['VIF'] <= 10
]['Feature'].tolist()

X = X[features_keep]
print(X.shape)

"""Variance Inflation Factors (VIF) were computed to detect multicollinearity among predictors. Variables with VIF values greater than 10 were removed because they contain redundant information already captured by other variables. The remaining variables exhibited acceptable levels of multicollinearity and were retained for modelling."""

